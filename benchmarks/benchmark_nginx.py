#!/usr/bin/env python3
"""Add nginx to the benchmark for a credibility baseline.

nginx is not a Python ASGI server — it sets the upper bound for what a
static-file server on this hardware can do. Running this alongside
``benchmark.py`` gives readers an honest "ceiling" reference.

Requires ``nginx`` on PATH. Skips itself otherwise.

Usage:

    uv run python benchmarks/benchmark_nginx.py

The nginx process is started on a free local port with a minimal config
that points at the same static directory generated by ``benchmark.py``.
"""

from __future__ import annotations

import asyncio
import os
import shutil
import signal
import subprocess
import sys
import tempfile
import time
from pathlib import Path

# Re-use the generator + benchmark loop from the main bench script
sys.path.insert(0, str(Path(__file__).parent))
from benchmark import benchmark_server, generate_static_dir  # noqa: E402

NGINX_CONF_TEMPLATE = """\
daemon off;
worker_processes 1;
error_log stderr warn;
pid {pid_file};
events {{ worker_connections 1024; }}
http {{
    access_log off;
    sendfile on;
    tcp_nopush on;
    types {{
        text/html       html;
        text/css        css;
        application/javascript js;
        image/png       png;
        font/woff2      woff2;
        application/json json;
    }}
    default_type application/octet-stream;
    server {{
        listen {port};
        root {root};
        location /api/hello {{
            default_type application/json;
            return 200 '{{"message":"hello"}}';
        }}
        location / {{
            try_files $uri $uri/ =404;
        }}
    }}
}}
"""


def ensure_nginx() -> str | None:
    return shutil.which("nginx")


def write_nginx_conf(static_dir: Path, port: int, work: Path) -> Path:
    conf = work / "nginx.conf"
    pid_file = work / "nginx.pid"
    conf.write_text(
        NGINX_CONF_TEMPLATE.format(
            port=port,
            root=str(static_dir),
            pid_file=str(pid_file),
        )
    )
    # nginx insists on its temp/log directories existing
    for sub in (
        "client_body_temp",
        "proxy_temp",
        "fastcgi_temp",
        "uwsgi_temp",
        "scgi_temp",
    ):
        (work / sub).mkdir(exist_ok=True)
    return conf


async def run_nginx(static_dir: Path, port: int) -> dict:
    import httpx
    import psutil

    work = Path(tempfile.mkdtemp(prefix="wsnoutbench_nginx_"))
    conf = write_nginx_conf(static_dir, port, work)

    proc = subprocess.Popen(
        ["nginx", "-c", str(conf), "-p", str(work)],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )

    for _ in range(50):
        try:
            async with httpx.AsyncClient() as c:
                if (
                    await c.get(f"http://127.0.0.1:{port}/api/hello", timeout=1)
                ).status_code == 200:
                    break
        except (httpx.ConnectError, httpx.TimeoutException):
            pass
        await asyncio.sleep(0.1)
    else:
        proc.kill()
        proc.wait()
        raise RuntimeError("nginx did not start")

    time.sleep(0.5)
    try:
        ram = psutil.Process(proc.pid).memory_info().rss / 1024 / 1024
    except psutil.Error:
        ram = 0.0

    bench = await benchmark_server(port, num_requests=500, concurrency=10)
    bench["ram_mb"] = round(ram, 1)

    try:
        os.kill(proc.pid, signal.SIGQUIT)
        proc.wait(timeout=5)
    except (ProcessLookupError, subprocess.TimeoutExpired):
        proc.kill()
        proc.wait()

    shutil.rmtree(work, ignore_errors=True)
    return bench


async def main() -> None:
    if ensure_nginx() is None:
        print("nginx not found on PATH — skipping nginx baseline benchmark")
        print("install with `sudo pacman -S nginx` (Arch) or equivalent")
        sys.exit(0)

    with tempfile.TemporaryDirectory() as tmp:
        static = Path(tmp) / "static"
        static.mkdir()
        generate_static_dir(static)
        result = await run_nginx(static, 18923)

    print("\n## nginx baseline\n")
    print("| Server | RPS | P50 (ms) | P99 (ms) | RAM (MB) |")
    print("|---|---|---|---|---|")
    print(
        f"| nginx | {result['rps']:.0f} | {result['p50_ms']:.1f} | "
        f"{result['p99_ms']:.1f} | {result['ram_mb']:.1f} |"
    )


if __name__ == "__main__":
    asyncio.run(main())
